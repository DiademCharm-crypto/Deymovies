    private static void styleTabs(State85 st) {
        int on = Color.WHITE;
        int off = Color.parseColor(C_DIM);
        int red = Color.parseColor(C_RED);
        boolean first = st.tab == 0;
        st.tabDlTxt.setTextColor(first ? on : off);
        st.tabDlTxt.setTypeface(first ? android.graphics.Typeface.DEFAULT_BOLD : android.graphics.Typeface.DEFAULT);
        st.tabDlLine.setBackgroundColor(first ? red : Color.TRANSPARENT);
        st.tabDoneTxt.setTextColor(first ? off : on);
        st.tabDoneTxt.setTypeface(first ? android.graphics.Typeface.DEFAULT : android.graphics.Typeface.DEFAULT_BOLD);
        st.tabDoneLine.setBackgroundColor(first ? Color.TRANSPARENT : red);
        // the searchbar exists only on the Downloaded tab
        if (st.search != null) {
            st.search.setVisibility(first ? View.GONE : View.VISIBLE);
            if (first && st.query.length() > 0) {
                st.query = "";
                st.search.setText("");
            }
        }
    }

